"""# DATA PROCESSING

Setelah fitur-fitur konten seperti `genres`, `keywords`, `cast`, dan `director` berhasil diekstrak dalam bentuk list of strings, tahap selanjutnya adalah melakukan pembersihan data agar siap digunakan dalam model.

Proses *text preprocessing* ini mencakup:
- Mengubah seluruh teks menjadi huruf kecil (lowercase)
- Menghapus spasi dalam setiap elemen list
- Menghilangkan string kosong atau tidak valid

Tujuan dari pembersihan ini adalah untuk menyamakan format kata-kata yang akan digunakan dalam proses vektorisasi, sehingga kata-kata seperti "Science Fiction" dan "sciencefiction" tidak dianggap berbeda oleh model. Hasil pembersihan disimpan dalam kolom baru `*_clean`, yaitu `genres_clean`, `keywords_clean`, `cast_clean`, dan `director_clean`.

Langkah ini merupakan bagian penting dalam Content-Based Filtering karena hasil akhir dari teks ini akan menjadi representasi konten (content representation) dari setiap film.
"""

# Text Preprocessing
print("\n🔧 Preprocessing teks...")

def clean_list(input_list):
    """
    Membersihkan list of strings: lowercase, hapus spasi, filter string kosong
    """
    if not isinstance(input_list, list):
        return []

    cleaned = []
    for item in input_list:
        if isinstance(item, str) and item.strip():
            # Hapus spasi dan ubah ke lowercase
            token = item.replace(" ", "").lower()
            cleaned.append(token)
    return cleaned

# Apply cleaning
movies_df['genres_clean'] = movies_df['genres_list'].apply(clean_list)
movies_df['keywords_clean'] = movies_df['keywords_list'].apply(clean_list)
movies_df['cast_clean'] = movies_df['cast_list'].apply(clean_list)
movies_df['director_clean'] = movies_df['director_list'].apply(clean_list)

print("✅ Text preprocessing selesai")

"""Setelah proses ekstraksi dan pembersihan fitur konten selesai, tahap berikutnya adalah menggabungkan semua fitur tersebut ke dalam satu representasi teks yang disebut *content soup*.

Content soup adalah gabungan dari fitur `genres_clean`, `keywords_clean`, `cast_clean`, dan `director_clean`, yang telah dibersihkan sebelumnya. Setiap elemen dari fitur tersebut akan digabung menjadi satu string dengan spasi sebagai pemisah.

Representasi ini sangat penting karena akan digunakan sebagai input untuk proses vektorisasi teks (TF-IDF) dan perhitungan kemiripan antar film menggunakan cosine similarity.

Setelah soup dibuat, baris film yang tidak memiliki konten (soup kosong) akan disaring agar tidak mengganggu proses pemodelan. Sebagai tambahan, ditampilkan satu contoh content soup dari film pertama untuk menunjukkan isi dari fitur gabungan ini.

"""

# Create content soup
def create_soup(row):
    """
    Menggabungkan semua fitur konten menjadi satu string
    """
    features = []

    # Tambahkan semua fitur yang sudah dibersihkan
    for feature_list in [row['genres_clean'], row['keywords_clean'],
                        row['cast_clean'], row['director_clean']]:
        if isinstance(feature_list, list):
            features.extend(feature_list)

    return " ".join(features)

movies_df['soup'] = movies_df.apply(create_soup, axis=1)

# Filter film yang memiliki content
movies_df = movies_df[movies_df['soup'].str.len() > 0].reset_index(drop=True)
