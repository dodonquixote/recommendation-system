# Fungsi bantu untuk parsing JSON
def parse_json_column(json_str):
    """
    Memparsing string JSON dan mengembalikan list elemen 'name'.
    Jika parsing gagal, kembalikan list kosong.
    """
    try:
        data = json.loads(json_str)
        if isinstance(data, list):
            names = [d.get('name', '') for d in data if isinstance(d, dict) and 'name' in d]
            return names
    except (TypeError, json.JSONDecodeError, AttributeError):
        pass
    return []

"""

Pada tahap ini, dilakukan proses ekstraksi fitur dari beberapa kolom penting yang menyimpan data dalam format JSON string, yaitu `genres`, `keywords`, `cast`, dan `crew`. Karena kolom-kolom ini tidak dapat langsung digunakan dalam bentuk mentah, maka dilakukan parsing untuk mengambil informasi relevan.

**1. Genres**  
Kolom `genres` menyimpan informasi kategori film (seperti Action, Drama, dsb.) dalam bentuk list of dictionaries. Dengan fungsi `parse_json_column`, sistem mengekstrak semua nama genre menjadi list of strings agar bisa diproses lebih lanjut.

**2. Keywords**  
Kolom `keywords` juga berisi list of dictionaries yang merepresentasikan kata kunci atau tema utama dari film. Kata-kata ini sangat penting karena menggambarkan konten inti dari sebuah film.

**3. Cast (Pemeran Utama)**  
Informasi pemain film tersimpan di kolom `cast` dalam format JSON. Dari data tersebut, hanya tiga pemeran utama (top 3 berdasarkan urutan tampil) yang diambil menggunakan fungsi `get_top_cast`. Pemain utama dapat sangat memengaruhi minat pengguna terhadap suatu film.

**4. Director (Sutradara)**  
Kolom `crew` mencakup semua kru film. Di sini, hanya data dengan peran sebagai `Director` yang diambil karena sutradara berkontribusi besar terhadap gaya dan kualitas sebuah film. Pengambilan dilakukan dengan fungsi `get_director`.

Setiap hasil ekstraksi disimpan ke dalam kolom baru dalam bentuk list dan akan digunakan untuk membuat representasi teks film (*content soup*) pada tahap selanjutnya.
"""

# Ekstraksi fitur konten
