# 7.3. Cast (ambil top 3)
def get_top_cast(cast_json_str, top_n=3):
    """Mengambil nama cast utama berdasarkan order"""
    try:
        cast_data = json.loads(cast_json_str)
        if isinstance(cast_data, list):
            # Sort berdasarkan order, ambil top N
            cast_data_sorted = sorted(cast_data, key=lambda d: d.get('order', float('inf')))
            top_cast = [d.get('name', '') for d in cast_data_sorted[:top_n]
                       if isinstance(d, dict) and 'name' in d]
            return top_cast
    except (TypeError, json.JSONDecodeError, AttributeError):
        pass
    return []

movies_df['cast_list'] = movies_df['cast'].apply(lambda x: get_top_cast(x, top_n=3))
